// closeTimeout bounds how long shutdown may take before Harp exits anyway.
const closeTimeout = 10 * time.Second

// NewContext returns a context holding the sing-box protocol registries. The
// same context must be used to parse and to run a configuration.
func NewContext() context.Context {
	ctx := service.ContextWith(context.Background(), deprecated.NewStderrManager(sblog.StdLogger()))
	return registryContext(ctx)
}

// Parse decodes a sing-box configuration. Comments (//, /* */ and #) are
// allowed.
func Parse(ctx context.Context, content []byte) (option.Options, error) {
	content, err := io.ReadAll(json.NewCommentFilter(bytes.NewReader(content)))
	if err != nil {
		return option.Options{}, errors.WithStack(err)
	}
	options, err := json.UnmarshalExtendedContext[option.Options](ctx, content)
	return options, errors.Wrap(err, "decode sing-box configuration")
}

// ParseObject decodes a configuration generated by Build.
func ParseObject(ctx context.Context, config map[string]any) (option.Options, error) {
	content, err := stdjson.Marshal(config)
	if err != nil {
		return option.Options{}, errors.WithStack(err)
	}
	return Parse(ctx, content)
}

// Merge merges several configuration files, later files taking precedence,
// the same way `sing-box run -c a.json -c b.json` does.
func Merge(ctx context.Context, contents [][]byte) (option.Options, error) {
	if len(contents) == 0 {
		return option.Options{}, errors.New("no configuration given")
	}
	var merged json.RawMessage
	for _, content := range contents {
		options, err := Parse(ctx, content)
		if err != nil {
			return option.Options{}, err
		}
		if len(contents) == 1 {
			return options, nil
		}
		merged, err = badjson.MergeJSON(ctx, options.RawMessage, merged, false)
		if err != nil {
			return option.Options{}, errors.Wrap(err, "merge configurations")
		}
	}
	return Parse(ctx, merged)
}

// InjectWarp adds the WARP endpoint to a user supplied configuration,
// replacing any endpoint or outbound with the same tag. If the configuration
// has no final outbound, WARP becomes the default.
func InjectWarp(ctx context.Context, options *option.Options, warp Warp) error {
	if warp.Tag == "" {
		warp.Tag = DefaultWarpTag
	}
	content, err := stdjson.Marshal(WarpEndpoint(warp))
	if err != nil {
		return errors.WithStack(err)
	}
	var endpoint option.Endpoint
	if err := json.UnmarshalContext(ctx, content, &endpoint); err != nil {
		return errors.Wrap(err, "decode WARP endpoint")
	}
	var endpoints []option.Endpoint
	for _, existing := range options.Endpoints {
		if existing.Tag != warp.Tag {
			endpoints = append(endpoints, existing)
		}
	}
	options.Endpoints = append(endpoints, endpoint)
	var outbounds []option.Outbound
	for _, existing := range options.Outbounds {
		if existing.Tag != warp.Tag {
			outbounds = append(outbounds, existing)
		}
	}
	options.Outbounds = outbounds
	if options.Route == nil {
		options.Route = &option.RouteOptions{}
	}
	if options.Route.Final == "" {
		options.Route.Final = warp.Tag
	}
	return nil
}

// Marshal encodes a configuration as indented JSON.
func Marshal(ctx context.Context, options option.Options) ([]byte, error) {
	content, err := json.MarshalContext(ctx, options)
	if err != nil {
		return nil, errors.WithStack(err)
	}
	var indented bytes.Buffer
	if err := stdjson.Indent(&indented, content, "", "  "); err != nil {
		return nil, errors.WithStack(err)
	}
	indented.WriteByte('\n')
	return indented.Bytes(), nil
}

// Run starts sing-box and blocks until SIGINT or SIGTERM.
func Run(ctx context.Context, options option.Options) error {
	signals := make(chan os.Signal, 1)
	signal.Notify(signals, os.Interrupt, syscall.SIGTERM)
	defer signal.Stop(signals)

	instance, err := Start(ctx, options, nil)
	if err != nil {
		return err
	}
	log.Println("Harp is running, press Ctrl+C to stop")
	<-signals
	log.Println("Stopping")
	return instance.Close()
}

// LogWriter receives every log message of a running instance.
type LogWriter interface {
	WriteMessage(level sblog.Level, message string)
}

// Instance is a running sing-box service.
type Instance struct {
	box     *box.Box
	ctx     context.Context
	cancel  context.CancelFunc
	traffic *trafficcontrol.Manager
}

// Start creates and starts sing-box. ctx must come from NewContext and must
// be the context the options were parsed with. When logWriter is set, it
// receives all log messages and connection tracking is enabled.
func Start(ctx context.Context, options option.Options, logWriter LogWriter) (*Instance, error) {
	runCtx, cancel := context.WithCancel(service.ExtendContext(ctx))
	boxOptions := box.Options{Context: runCtx, Options: options}
	if logWriter != nil {
		boxOptions.PlatformLogWriter = logWriter
	}
	instance, err := box.New(boxOptions)
	if err != nil {
		cancel()
		return nil, errors.Wrap(err, "create service")
	}
	if err := instance.Start(); err != nil {
		_ = instance.Close()
		cancel()
		return nil, errors.Wrap(err, "start service")
	}
	return &Instance{
		box:     instance,
		ctx:     runCtx,
		cancel:  cancel,
		traffic: service.PtrFromContext[trafficcontrol.Manager](runCtx),
	}, nil
}

// Close stops the instance, giving up after closeTimeout.
func (i *Instance) Close() error {
	i.cancel()
	closed := make(chan error, 1)
	go func() { closed <- i.box.Close() }()
	select {
	case err := <-closed:
		return errors.Wrap(err, "close service")
	case <-time.After(closeTimeout):
		return errors.New("service did not stop in time")
	}
}

// Traffic returns the connection tracker. It is nil unless the instance was
// started with a LogWriter or with the Clash API enabled.
func (i *Instance) Traffic() *trafficcontrol.Manager {
	return i.traffic
}

// HTTPClient returns an HTTP client whose connections go through the
// outbound or endpoint with the given tag.
func (i *Instance) HTTPClient(tag string, timeout time.Duration) (*http.Client, error) {
	outbound, ok := i.box.Outbound().Outbound(tag)
	if !ok {
		return nil, errors.Newf("outbound %q not found", tag)
	}
	transport := &http.Transport{
		DialContext: func(ctx context.Context, network, address string) (net.Conn, error) {
			return outbound.DialContext(ctx, network, M.ParseSocksaddr(address))
		},
		ForceAttemptHTTP2:   true,
		TLSHandshakeTimeout: timeout,
		DisableKeepAlives:   true,
	}
	return &http.Client{Transport: transport, Timeout: timeout}, nil
}

// ResolveEndpoint turns "host:port" into an IP address and port. Names are
// resolved with the system resolver; if that fails or returns an address a
// filtering resolver would hand out (private, loopback and the like),
// fallback (an "ip:port" pair) is used instead.
func ResolveEndpoint(endpoint, fallback string) (string, uint16, error) {
	host, port, err := splitEndpoint(endpoint)
	if err != nil {
		return "", 0, err
	}
	if _, err := netip.ParseAddr(host); err == nil {
		return host, port, nil
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	addresses, err := net.DefaultResolver.LookupNetIP(ctx, "ip", host)
	var usable []netip.Addr
	for _, address := range addresses {
		if PublicAddress(address.Unmap()) {
			usable = append(usable, address.Unmap())
		}
	}
	if len(usable) != 0 {
		chosen := usable[0]
		for _, address := range usable {
			if address.Is4() {
				chosen = address
				break
			}
		}
		return chosen.String(), port, nil
	}
	if err == nil {
		err = errors.Newf("%s resolved to %v, which looks like a filtered DNS answer", host, addresses)
	}
	if fallback != "" {
		log.Printf("Could not resolve %s (%v), using %s instead", host, err, fallback)
		return splitEndpoint(fallback)
	}
	return "", 0, errors.Wrapf(err, "resolve WARP endpoint %s", host)
}

// PublicAddress reports whether address can be a real Internet server.
// Filtering resolvers answer blocked names with private or reserved
// addresses, such as 10.10.34.36.
func PublicAddress(address netip.Addr) bool {
	return address.IsValid() && address.IsGlobalUnicast() && !address.IsPrivate() &&
		!netip.MustParsePrefix("100.64.0.0/10").Contains(address) &&
		!netip.MustParsePrefix("198.18.0.0/15").Contains(address)
}

// StartWarp runs only the WARP endpoint, tagged DefaultWarpTag, without any
// inbound. It is used to test whether traffic gets through an endpoint.
func StartWarp(w Warp) (*Instance, error) {
	w.Tag = DefaultWarpTag
	config := map[string]any{
		"log":       map[string]any{"disabled": true},
		"endpoints": []any{WarpEndpoint(w)},
	}
	ctx := NewContext()
	options, err := ParseObject(ctx, config)
	if err != nil {
		return nil, err
	}
	return Start(ctx, options, nil)
}

func splitEndpoint(endpoint string) (string, uint16, error) {
	host, portString, err := net.SplitHostPort(endpoint)
	if err != nil {
		return "", 0, errors.Wrapf(err, "invalid endpoint %q (expected host:port)", endpoint)
	}
	port, err := strconv.ParseUint(portString, 10, 16)
	if err != nil || port == 0 {
		return "", 0, errors.Newf("invalid endpoint %q: bad port", endpoint)
	}
	return host, uint16(port), nil
}
